import { toTwTime, twStartOf } from './utils/time-helpers';
import Prando from 'prando';
const { Parser } = require('json2csv');
const fs = require('fs');

function extractDonationData(donations) {
  return donations.filter(d => d.state === 'paid').reduce((array, donation) => {
    const {
      id,
      amount,
      state,
      donorBirthday,
      donorEmail,
      donorFirstName,
      donorIdNumber,
      donorLastName,
      donorName,
      donorPublicName,
      receiptType,
      receiptTitle,
      receiptState,
      receiptAddress,
      extraData,
      created_at,
      deleted_at,
      source_subscription_id,
      donor_id,
    } = donation;

    let rng = new Prando(`donation-subscription-${id}`);
    const theFirstDay = toTwTime(created_at);
    const theFirstDelay = Math.floor(rng.next(2000, 12000));
    const theFirstDelayTime = toTwTime(theFirstDay).add(theFirstDelay, 'milliseconds');
  
    let currentDay = twStartOf('day', theFirstDay);
    const endDay = deleted_at ? twStartOf('day', deleted_at) : twStartOf('D', '2024-08-01');

    const requests : {
      amount: number;
      request_time: string;
    }[] = [];
    console.log('endDay :', endDay.toISOString(true));

    for (let index = 0; index < 60; index++) {
      currentDay = toTwTime(currentDay).add(1, 'month');
      const delay = Math.floor(rng.next(2000, 120000));
      const expectedPayTime = toTwTime(currentDay).add(10, 'hours');
      if (expectedPayTime.valueOf() > endDay.valueOf()) {
        break;
      }
      const payTime = toTwTime(expectedPayTime).add(delay, 'milliseconds');
      requests.push({
        amount,
        request_time: payTime.toISOString(true),
      });
    }

    // console.log('theFirstDay :', theFirstDay.toISOString(true));
    // console.log('theFirstDelayTime :', theFirstDelayTime.toISOString(true));


    return [...array, {
      id,
      amount,
      request_time: theFirstDelayTime.toISOString(true),
      state,
      donorBirthday,
      donorEmail,
      donorFirstName,
      donorIdNumber,
      donorLastName,
      donorName,
      donorPublicName,
      receiptType,
      receiptTitle,
      receiptState,
      receiptAddress,
      extraEmail: extraData.email,
      extraMobile: extraData.mobile,
      extraLastName: extraData.lastName,
      extraFirstName: extraData.firstName,
      created_at,
      source_subscription_id,
      donor_id,
    }, ...requests];
  }, []);
}


